test("avatar budget counts actual stored objects and refuses unknown or excessive usage", async (t) => {
  const settings = {
    R2_ACCOUNT_ID: "a".repeat(32),
    R2_ACCESS_KEY_ID: "test-key",
    R2_SECRET_ACCESS_KEY: "test-secret",
    R2_BUCKET: "example-media",
    R2_KEY_PREFIX: "heimdall-test",
  };
  for (const [key, value] of Object.entries(settings)) {
    const original = process.env[key];
    process.env[key] = value;
    t.after(() => {
      if (original === undefined) delete process.env[key];
      else process.env[key] = original;
    });
  }
  let xml =
    "<ListBucketResult><Contents><Size>100</Size></Contents><IsTruncated>false</IsTruncated></ListBucketResult>";
  const fetch = t.mock.method(globalThis, "fetch", async (input: URL) => {
    assert.equal(input.searchParams.get("prefix"), "heimdall-test/avatars/");
    assert.equal(input.searchParams.get("list-type"), "2");
    return new Response(xml);
  });
  await enforceAvatarBudget(MAX_AVATAR_BYTES);
  xml =
    "<ListBucketResult><Contents><Size>20971520</Size></Contents><IsTruncated>false</IsTruncated></ListBucketResult>";
  await assert.rejects(() => enforceAvatarBudget(1), /저장 한도/);
  xml = "<Error>unavailable</Error>";
  await assert.rejects(() => enforceAvatarBudget(1), /용량을 확인/);
  assert.equal(fetch.mock.callCount(), 3);
});
test("session tokens are hashed and proxy headers cannot claim loopback", () => {
  const req = {
    headers: {
      cookie: "heimdall_session=" + "a".repeat(43),
      "x-forwarded-for": "127.0.0.1",
    },
    socket: { remoteAddress: "172.18.0.2" },
  } as unknown as IncomingMessage;
  assert.match(sessionHash(req), /^[a-f0-9]{64}$/);
  assert.equal(localRequest(req), false);
  req.headers.cookie = "heimdall_session=invalid";
  assert.equal(sessionHash(req), "");
});
test("dedicated Heimdall host requires its own exact browser origin", () => {
  const request = (
    host: string,
    origin?: string,
    remoteAddress = "172.18.0.2",
  ) =>
    ({
      headers: { host, origin },
      socket: { remoteAddress },
    }) as IncomingMessage;
  for (const host of ["heimdall.example", "gateway.example"]) {
    assert.equal(allowed(request(host)), true);
    assert.equal(allowedBrowserOrigin(request(host)), false);
    assert.equal(allowed(request(host, "https://" + host)), true);
    assert.equal(allowedBrowserOrigin(request(host, "https://" + host)), true);
    assert.equal(allowed(request(host, "http://" + host)), false);
    assert.equal(allowed(request(host, "null")), false);
  }
  assert.equal(
    allowed(request("heimdall.example", "https://gateway.example")),
    false,
  );
  assert.equal(
    allowed(request("gateway.example", "https://heimdall.example")),
    false,
  );
  assert.equal(
    allowed(
      request(
        "heimdall.example.evil.test",
        "https://heimdall.example",
      ),
    ),
    false,
  );
  assert.equal(allowed(request("localhost", undefined, "127.0.0.1")), true);
  assert.equal(
    allowed(
      request("heimdall.example", "https://evil.test", "127.0.0.1"),
    ),
    false,
  );
});
test("domain registration normalizes origins and rejects embedded credentials", () => {
  assert.deepEqual(normalizeDomain("https://EXAMPLE.com/start?mode=test"), {
    url: "https://example.com/start?mode=test",
    origin: "https://example.com",
  });
  for (const value of [
    "javascript:alert(1)",
    "file:///etc/passwd",
    "https://admin:password@example.com",
    "https://example.com/#fragment",
    "not a url",
  ])
    assert.throws(() => normalizeDomain(value));
});
test("worker applies domain removal and rejects invalid configuration atomically", () => {
  configureOrigins(["https://example.com"]);
  assert.equal(
    checkUrl("https://example.com/test"),
    "https://example.com/test",
  );
  assert.throws(() => checkUrl("https://unregistered.example"));
  assert.throws(() => configureOrigins(["https://example.com", "file:///"]));
  assert.equal(checkUrl("https://example.com"), "https://example.com/");
  configureOrigins([]);
  assert.throws(() => checkUrl("https://example.com/test"));
});
