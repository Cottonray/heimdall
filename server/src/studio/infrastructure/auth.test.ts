test("passwords use independent salts and reject wrong passwords", async () => {
  const first = await hashPassword("test-secret-123456789");
  const second = await hashPassword("test-secret-123456789");
  assert.notEqual(first, second);
  assert.equal(await verifyPassword("test-secret-123456789", first), true);
  assert.equal(await verifyPassword("wrong", first), false);
  assert.equal(await verifyPassword("wrong", "invalid"), false);
  assert.equal(await verifyPassword("wrong", "salt:" + "z".repeat(128)), false);
});
test("password changes enforce current credentials, new length and dedicated-account boundaries", () => {
  assert.deepEqual(
    validatePasswordChange("tester", "old-secret", "new-secret-123456"),
    {
      currentPassword: "old-secret",
      newPassword: "new-secret-123456",
    },
  );
  assert.equal(
    validatePasswordChange("admin", "old", "x".repeat(256)).newPassword.length,
    256,
  );
  for (const id of ["demo-user", "demo-admin"])
    assert.throws(
      () => validatePasswordChange(id, "old-secret", "new-secret-123456"),
      /테스트용/,
    );
  for (const [current, next] of [
    ["", "new-secret-123456"],
    ["old", "short"],
    ["old", "x".repeat(257)],
    ["same-secret-123", "same-secret-123"],
    [null, "new-secret-123456"],
  ])
    assert.throws(() => validatePasswordChange("tester", current, next));
});
test("avatar input accepts a real PNG and rejects active content, fake MIME and oversized data", () => {
  const png =
    "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=";
  const image = decodeAvatar("data:image/png;base64," + png);
  assert.equal(image.mime, "image/png");
  assert.deepEqual(image.bytes, Buffer.from(png, "base64"));
  for (const invalid of [
    "data:image/svg+xml;base64," +
      Buffer.from('<svg onload="alert(1)"/>').toString("base64"),
    "data:image/png;base64," +
      Buffer.from("<html>not an image</html>").toString("base64"),
    "data:image/jpeg;base64," + png,
    "data:image/webp;base64," + png,
    "data:image/png;base64," + png.slice(0, -4),
    "data:image/png;base64," +
      Buffer.alloc(MAX_AVATAR_BYTES + 1).toString("base64"),
    "https://example.com/avatar.png",
  ])
    assert.throws(() => decodeAvatar(invalid));
});
